import AppKit
import SwiftUI

// Each entry is a private UTF-8 file. File sizes are charged in filesystem-sized
// blocks so the cap also accounts for small entries, not just their text bytes.
final class ClipboardStore: @unchecked Sendable {
    static let limit: Int64 = 2_000_000_000
    let directory: URL
    init(directory: URL = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support/Keylight/Clipboard", isDirectory: true)) { self.directory = directory }
    private func files() throws -> [(URL, Int64)] {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try ConfigStore.requirePrivateDirectory(directory)
        return try FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: [.isRegularFileKey, .fileAllocatedSizeKey], options: [.skipsHiddenFiles]).filter { $0.pathExtension == "txt" }.sorted { $0.lastPathComponent < $1.lastPathComponent }.map { url in
            let values = try url.resourceValues(forKeys: [.isRegularFileKey, .fileAllocatedSizeKey])
            guard values.isRegularFile == true else { throw ConfigError.io("Invalid clipboard history entry.") }
            guard let size = values.fileAllocatedSize else { throw ConfigError.io("Cannot measure clipboard history.") }
            return (url, Int64(size))
        }
    }
    func save(_ text: String) throws -> Bool {
        guard text.utf8.count <= 16_000_000 else { throw ConfigError.io(NSLocalizedString("Clipboard text exceeds 16 MB and was not saved.", comment: "")) }
        let data = Data(text.utf8)
        let charge = Int64((data.count + 4095) / 4096 * 4096)
        guard charge <= Self.limit else { throw ConfigError.io(NSLocalizedString("Clipboard item exceeds 2 GB and was not saved.", comment: "")) }
        var entries = try files()
        var used = entries.reduce(Int64(0)) { $0 + $1.1 }
        var removed = false
        // Reserve one maximum-sized item so a new item is durable before eviction.
        let retainedLimit = Self.limit - 16_000_000
        while used > retainedLimit, !entries.isEmpty {
            let first = entries.removeFirst()
            try FileManager.default.removeItem(at: first.0)
            used -= first.1; removed = true
        }
        let name = String(format: "%020llu", UInt64(Date().timeIntervalSince1970 * 1_000_000)) + "-" + UUID().uuidString + ".txt"
        let destination = directory.appendingPathComponent(name)
        try privateAtomicWrite(data, to: destination)
        used += charge
        while used > retainedLimit, !entries.isEmpty {
            let first = entries.removeFirst()
            try FileManager.default.removeItem(at: first.0)
            used -= first.1; removed = true
        }
        return removed
    }
    func page(before: String? = nil) throws -> [(String, String)] {
        let selected = try files().reversed().filter { before == nil || $0.0.lastPathComponent < before! }.prefix(100)
        return try selected.map { (url, _) in
            let handle = try FileHandle(forReadingFrom: url); defer { try? handle.close() }
            let prefix = try handle.read(upToCount: 1024) ?? Data()
            return (url.lastPathComponent, String(decoding: prefix, as: UTF8.self).replacingOccurrences(of: "\n", with: " "))
        }
    }
    func read(_ name: String) throws -> String {
        guard !name.contains("/"), name.hasSuffix(".txt") else { throw ConfigError.invalid }
        return try String(contentsOf: directory.appendingPathComponent(name), encoding: .utf8)
    }
}

@MainActor final class ClipboardHistory: ObservableObject {
    struct Item: Identifiable { let id: String; let preview: String }
    @Published var items: [Item] = []
    @Published var error: String?
    @Published var limitNotice = false
    private let store = ClipboardStore()
    private let queue = DispatchQueue(label: "com.alex.Keylight.clipboard", qos: .utility)
    private var timer: Timer?
    private var change = NSPasteboard.general.changeCount
    private var lastText: String?
    private var writing = false
    func start() {
        limitNotice = UserDefaults.standard.bool(forKey: "clipboardLimitNotice")
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in Task { @MainActor in self?.poll() } }
    }
    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != change else { return }
        change = board.changeCount
        // Respect the conventional sensitive/transient pasteboard markers.
        let blocked = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !blocked.contains(where: { board.types?.contains(NSPasteboard.PasteboardType($0)) == true }),
              board.types?.contains(.fileURL) != true, board.types?.contains(.png) != true, board.types?.contains(.tiff) != true,
              let text = board.string(forType: .string), !text.isEmpty, text != lastText else { return }
        guard !writing else { error = NSLocalizedString("Clipboard history is busy; an item was not saved.", comment: ""); return }
        writing = true; lastText = text
        queue.async { [store] in
            let result = Result { try store.save(text) }
            DispatchQueue.main.async {
                self.writing = false
                switch result { case .success(let removed): if removed { self.limitNotice = true; UserDefaults.standard.set(true, forKey: "clipboardLimitNotice") }; case .failure(let failure): self.lastText = nil; self.error = failure.localizedDescription }
            }
        }
    }
    func dismissNotice() { limitNotice = false; UserDefaults.standard.set(false, forKey: "clipboardLimitNotice") }
    func load(more: Bool = false) {
        let before = more ? items.last?.id : nil
        queue.async { [store] in
            let result = Result { try store.page(before: before) }
            DispatchQueue.main.async {
                switch result { case .success(let rows): let values = rows.map { Item(id: $0.0, preview: $0.1) }; self.items = more ? self.items + values : values
                case .failure(let failure): self.error = failure.localizedDescription }
            }
        }
    }
    func copy(_ item: Item, completion: @escaping () -> Void) {
        queue.async { [store] in
            let result = Result { try store.read(item.id) }
            DispatchQueue.main.async {
                switch result { case .success(let text): let board = NSPasteboard.general; board.clearContents(); guard board.setString(text, forType: .string) else { self.error = NSLocalizedString("Could not copy to the clipboard.", comment: ""); return }; self.change = board.changeCount; self.lastText = text; completion()
                case .failure(let failure): self.error = failure.localizedDescription }
            }
        }
    }
}

struct ClipboardView: View {
    @ObservedObject var history: ClipboardHistory
    let appearance: LauncherAppearance
    let back: () -> Void
    let close: () -> Void
    @State private var selected = 0
    @FocusState private var focused: Bool
    var body: some View {
        VStack(spacing: 0) {
            LauncherHeader(appearance: appearance) { HStack { Button(action: back) { Image(systemName: "chevron.left") }.buttonStyle(.plain); Text("Clipboard History").font(appearance.inputFont); Spacer(); Text("↵ Copy · ⌘V Paste").font(.caption).foregroundStyle(.secondary) } }
            ScrollViewReader { proxy in
                ScrollView {
                    LazyVStack(spacing: 2) {
                        if let error = history.error { Text(error).foregroundStyle(.red).frame(maxWidth: .infinity, alignment: .leading) }
                        if history.items.isEmpty { Text("No clipboard history").foregroundStyle(.secondary).padding() }
                        ForEach(Array(history.items.enumerated()), id: \.element.id) { index, item in
                            Button { history.copy(item, completion: close) } label: {
                                Text(item.preview).lineLimit(2).frame(maxWidth: .infinity, alignment: .leading).padding(10).background(index == selected ? appearance.selection : .clear).clipShape(RoundedRectangle(cornerRadius: appearance.rowCornerRadius))
                            }.buttonStyle(.plain).id(item.id)
                        }
                        if history.items.count >= 100 { Button("Load more") { history.load(more: true) }.padding(8) }
                    }.padding(8)
                }.frame(height: LauncherAppearance.resultsHeight).onChange(of: selected) { _, value in if history.items.indices.contains(value) { proxy.scrollTo(history.items[value].id) } }
            }
        }.focusable().focused($focused).onAppear { history.load(); DispatchQueue.main.async { focused = true } }
            .onKeyPress(.escape) { back(); return .handled }
            .onKeyPress(.downArrow) { if selected == history.items.count - 1 && history.items.count >= 100 { history.load(more: true) }; selected = min(selected + 1, max(0, history.items.count - 1)); return .handled }
            .onKeyPress(.upArrow) { selected = max(0, selected - 1); return .handled }
            .onKeyPress(.return) { if history.items.indices.contains(selected) { history.copy(history.items[selected], completion: close) }; return .handled }
    }
}
